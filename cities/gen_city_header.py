#!/usr/bin/env python3
"""Generate platformio/include/cities_zh_CN.h from cities_zh_CN.csv.

Usage:
  python3 gen_city_header.py
"""

import csv
from pathlib import Path

SCRIPT_DIR = Path(__file__).resolve().parent
CSV_PATH = SCRIPT_DIR / 'cities_zh_CN.csv'
OUT_PATH = SCRIPT_DIR.parent / 'platformio' / 'include' / 'cities_zh_CN.h'


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    rows = list(csv.DictReader(CSV_PATH.open(encoding='utf-8')))
    provinces = []
    for r in rows:
        if r['province'] not in provinces:
            provinces.append(r['province'])

    lines = [
        '/* List of selectable cities for the setup portal.',
        ' * Generated by cities/gen_city_header.py from cities_zh_CN.csv,',
        ' * do not edit. Source: Wikidata (CC0).',
        ' */',
        '',
        '#ifndef __CITIES_ZH_CN_H__',
        '#define __CITIES_ZH_CN_H__',
        '',
        '#include <cstdint>',
        '',
        'typedef struct city',
        '{',
        '  uint8_t     province;  // index into CITY_PROVINCES',
        '  const char *name;      // full name, shown in the setup portal',
        '  const char *shortName; // shown on the display',
        '  const char *lat;',
        '  const char *lon;',
        '} city_t;',
        '',
        'const char *const CITY_PROVINCES[] = {',
    ]
    lines += [f'  {c_string(p)},' for p in provinces]
    lines += [
        '};',
        f'const uint8_t CITY_PROVINCE_COUNT = {len(provinces)};',
        '',
        'const city_t CITIES[] = {',
    ]
    for r in rows:
        lines.append(
            f'  {{{provinces.index(r["province"]):2d}, {c_string(r["name"])}, '
            f'{c_string(r["short_name"])}, "{r["lat"]}", "{r["lon"]}"}},')
    lines += [
        '};',
        f'const uint16_t CITY_COUNT = {len(rows)};',
        '',
        '#endif',
        '',
    ]
    OUT_PATH.write_text('\n'.join(lines), encoding='utf-8')
    print(f'wrote {len(rows)} cities in {len(provinces)} provinces to '
          f'{OUT_PATH.name}')


if __name__ == '__main__':
    main()
