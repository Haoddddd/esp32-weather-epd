#!/usr/bin/env python3
"""Generate subsetted CJK bitmap fonts for esp32-weather-epd.

Collects every non-Latin-1 character used in string literals of the CJK
locale files and config.cpp (plus extra_chars.txt, if present), rasterizes
those characters from the source fonts listed in FONTS, and writes one C
header per font to platformio/lib/esp32-weather-epd-assets/fonts/cjk/.

Source fonts are downloaded once into ./cache (git-ignored) and verified by
SHA-256.

Usage:
  python3 gen_cjk_fonts.py

Dependencies:
  Python 3, Pillow
"""

import csv
import hashlib
import io
import re
import sys
import urllib.request
import zipfile
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SCRIPT_DIR = Path(__file__).resolve().parent
REPO_DIR = SCRIPT_DIR.parent.parent
PIO_DIR = REPO_DIR / 'platformio'
OUT_DIR = PIO_DIR / 'lib' / 'esp32-weather-epd-assets' / 'fonts' / 'cjk'
CACHE_DIR = SCRIPT_DIR / 'cache'

# Files whose string literals are scanned for characters to include.
CHARSET_SOURCES = [
    PIO_DIR / 'include' / 'locales' / 'locale_zh_CN.inc',
    PIO_DIR / 'src' / 'config.cpp',
    PIO_DIR / 'src' / 'provisioning.cpp',
]
# Short city names selectable in the setup portal. Only added to fonts with
# 'cities': True (the size the city name is drawn at), to save flash.
CITIES_CSV = REPO_DIR / 'cities' / 'cities_zh_CN.csv'
# Optional newline/whitespace separated list of additional characters, e.g.
# every city name that can be selected during provisioning.
EXTRA_CHARS_FILE = SCRIPT_DIR / 'extra_chars.txt'

SOURCES = {
    'fusion-pixel-12px': {
        'url': 'https://github.com/TakWolf/fusion-pixel-font/releases/download/'
               '2026.09.25/fusion-pixel-font-12px-proportional-otf.woff2-'
               'v2026.09.25.zip',
        'sha256': '44b456f6f920d700f98d5865e03152d6'
                  'a7357ed0a8ee388376ac0530d2d57072',
        'member': 'fusion-pixel-12px-proportional-zh_hans.otf.woff2',
        'license': 'SIL OFL v1.1',
    },
    'noto-sans-sc': {
        'url': 'https://github.com/notofonts/noto-cjk/raw/Sans2.004/Sans/'
               'SubsetOTF/SC/NotoSansSC-Regular.otf',
        'sha256': 'faa6c9df652116dde789d351359f3d7e'
                  '5d2285a2b2a1f04a2d7244df706d5ea9',
        'member': None,
        'license': 'SIL OFL v1.1',
    },
}

# id:     C identifier and header file name
# source: key into SOURCES
# size:   pixel size passed to FreeType
# mode:   'mono' renders without anti-aliasing (for pixel fonts at their
#         native size), 'threshold' renders anti-aliased and thresholds at 50%
# cities: optional; True to also include every short city name
FONTS = [
    {'id': 'FusionPixel_12px', 'source': 'fusion-pixel-12px', 'size': 12,
     'mode': 'mono'},
    {'id': 'NotoSansSC_20px', 'source': 'noto-sans-sc', 'size': 20,
     'mode': 'threshold'},
    {'id': 'NotoSansSC_22px', 'source': 'noto-sans-sc', 'size': 22,
     'mode': 'threshold'},
    {'id': 'NotoSansSC_28px', 'source': 'noto-sans-sc', 'size': 28,
     'mode': 'threshold', 'cities': True},
    {'id': 'NotoSansSC_44px', 'source': 'noto-sans-sc', 'size': 44,
     'mode': 'threshold'},
]

HEADER_LICENSE = """\
/* {id} - generated by fonts/cjk/gen_cjk_fonts.py, do not edit.
 * Source font: {source} ({license})
 * Glyphs: {count}
 */
"""

STRING_LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')


def collect_charset():
    chars = set()
    for path in CHARSET_SOURCES:
        text = path.read_text(encoding='utf-8')
        for literal in STRING_LITERAL.findall(text):
            chars.update(c for c in literal if ord(c) > 0xFF)
    if EXTRA_CHARS_FILE.exists():
        text = EXTRA_CHARS_FILE.read_text(encoding='utf-8')
        chars.update(c for c in text if ord(c) > 0xFF and not c.isspace())
    non_bmp = [c for c in chars if ord(c) > 0xFFFF]
    if non_bmp:
        sys.exit('error: characters outside the BMP are not supported: '
                 + ''.join(non_bmp))
    return sorted(chars)


def collect_city_chars():
    with CITIES_CSV.open(encoding='utf-8') as f:
        names = [row['short_name'] for row in csv.DictReader(f)]
    return {c for name in names for c in name if ord(c) > 0xFF}


def fetch_source(key):
    src = SOURCES[key]
    CACHE_DIR.mkdir(exist_ok=True)
    archive = CACHE_DIR / src['url'].rsplit('/', 1)[1]
    if not archive.exists():
        print(f'downloading {src["url"]}')
        with urllib.request.urlopen(src['url']) as resp:
            data = resp.read()
        archive.write_bytes(data)
    data = archive.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if src['sha256'] and digest != src['sha256']:
        sys.exit(f'error: SHA-256 mismatch for {archive.name}: {digest}')
    if src['member'] is None:
        return archive
    font_path = CACHE_DIR / src['member']
    if not font_path.exists():
        with zipfile.ZipFile(io.BytesIO(data)) as zf:
            font_path.write_bytes(zf.read(src['member']))
    return font_path


def render_glyph(font, char, mode):
    """Returns (bits, width, height, xAdvance, xOffset, yOffset)."""
    x_advance = round(font.getlength(char))
    left, top, right, bottom = font.getbbox(char, anchor='ls')
    pad = 2
    origin_x, origin_y = pad - left, pad - top
    img = Image.new('L', (right - left + 2 * pad, bottom - top + 2 * pad), 0)
    draw = ImageDraw.Draw(img)
    draw.fontmode = '1' if mode == 'mono' else 'L'
    draw.text((origin_x, origin_y), char, font=font, fill=255, anchor='ls')
    img = img.point(lambda v: 255 if v >= 128 else 0)
    ink = img.getbbox()
    if ink is None:
        return [], 0, 0, x_advance, 0, 0
    x0, y0, x1, y1 = ink
    width, height = x1 - x0, y1 - y0
    bits = [1 if img.getpixel((x, y)) else 0
            for y in range(y0, y1) for x in range(x0, x1)]
    return bits, width, height, x_advance, x0 - origin_x, y0 - origin_y


def pack_bits(bits):
    out = bytearray()
    for i in range(0, len(bits), 8):
        byte = 0
        for j, bit in enumerate(bits[i:i + 8]):
            byte |= bit << (7 - j)
        out.append(byte)
    return out


def generate_font(spec, charset):
    src = SOURCES[spec['source']]
    font = ImageFont.truetype(str(fetch_source(spec['source'])), spec['size'])
    ascent, descent = font.getmetrics()
    fid = spec['id']

    bitmap = bytearray()
    glyph_lines = []
    missing = []
    for char in charset:
        cp = ord(char)
        bits, w, h, xa, xo, yo = render_glyph(font, char, spec['mode'])
        if w == 0 and not char.isspace():
            missing.append(char)
        glyph_lines.append(
            f'  {{ {len(bitmap):6d}, 0x{cp:04X}, {w:3d}, {h:3d}, {xa:3d}, '
            f'{xo:4d}, {yo:4d} }}, // {char}')
        bitmap += pack_bits(bits)
    if missing:
        print(f'warning: {fid} has no glyph for: {"".join(missing)}')

    lines = [HEADER_LICENSE.format(id=fid, source=spec['source'],
                                   license=src['license'],
                                   count=len(charset))]
    lines.append(f'#ifndef __FONTS_CJK_{fid.upper()}_H__')
    lines.append(f'#define __FONTS_CJK_{fid.upper()}_H__')
    lines.append('')
    lines.append('#include "CjkFont.h"')
    lines.append('')
    lines.append(f'const uint8_t {fid}Bitmaps[] PROGMEM = {{')
    for i in range(0, len(bitmap), 12):
        chunk = bitmap[i:i + 12]
        lines.append('  ' + ', '.join(f'0x{b:02X}' for b in chunk) + ',')
    lines.append('};')
    lines.append('')
    lines.append(f'const CjkGlyph {fid}Glyphs[] PROGMEM = {{')
    lines.append('  // bitmapOffset, codepoint, width, height, xAdvance, '
                 'xOffset, yOffset')
    lines.extend(glyph_lines)
    lines.append('};')
    lines.append('')
    lines.append(f'const CjkFont {fid} PROGMEM = {{')
    lines.append(f'  {fid}Bitmaps, {fid}Glyphs, {len(charset)}, '
                 f'{ascent + descent} }};')
    lines.append(f'// Approx. {len(bitmap) + len(charset) * 12} bytes')
    lines.append('')
    lines.append('#endif')
    lines.append('')
    (OUT_DIR / f'{fid}.h').write_text('\n'.join(lines), encoding='utf-8')
    return len(bitmap) + len(charset) * 12


def main():
    charset = collect_charset()
    city_chars = collect_city_chars()
    print(f'{len(charset)} characters: {"".join(charset)}')
    print(f'{len(city_chars)} characters in city names')
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    total = 0
    for spec in FONTS:
        font_charset = charset
        if spec.get('cities'):
            font_charset = sorted(set(charset) | city_chars)
        size = generate_font(spec, font_charset)
        total += size
        print(f'{spec["id"]}: ~{size} bytes')
    includes = '\n'.join(f'#include "{spec["id"]}.h"' for spec in FONTS)
    (OUT_DIR / 'CjkFonts.h').write_text(
        '/* Generated by fonts/cjk/gen_cjk_fonts.py, do not edit. */\n'
        '#ifndef __FONTS_CJK_CJKFONTS_H__\n'
        '#define __FONTS_CJK_CJKFONTS_H__\n'
        f'{includes}\n'
        '#endif\n', encoding='utf-8')
    print(f'total: ~{total} bytes')


if __name__ == '__main__':
    main()
